#!/usr/bin/env python3
"""Copy the AI prompt into app.js.

tools/ai_prompt.md is the prompt Norbert keeps in his Claude project ("Nutrilog tételpontosító", the contract of the "Paste from AI" import).
The app has it as a constant, so "Copy AI prompt" works offline. This script rewrites the block between the two marker comments in app.js:

    python3 -I tools/embed_ai_prompt.py            # from the repo root

What the app builds itself: the nutrient key list (from KEYS and UNITS, so it cannot drift from the importer) and the version in the title (AI_IMPORT_VERSION).
So the bullet list under "## Tápanyagkulcsok" is NOT copied; the one sentence about `protein` that sits in the first bullet is kept as AI_PROMPT_NOTE.
tests/test_ai_import.py checks that the constant, the key list and tools/ai_prompt.md still agree. When the prompt changes (v2): replace tools/ai_prompt.md,
run this script, raise AI_IMPORT_VERSION if the schema changed, and teach parseAiImport the new fields."""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
md = (root / 'tools' / 'ai_prompt.md').read_text(encoding='utf-8').replace('\r\n', '\n')
app_path = root / 'app.js'
app = app_path.read_text(encoding='utf-8')

head, sep, rest = md.partition('## Tápanyagkulcsok\n')
if not sep:
    sys.exit('The heading "## Tápanyagkulcsok" is missing in tools/ai_prompt.md')
intro, _, rest = rest.lstrip('\n').partition('\n\n')               # the sentence about the keys
bullets, _, tail = rest.partition('\n\n')                           # the bullet list (generated by the app instead)
if not bullets.startswith('- ') or not tail.startswith('Az érték szám ponttal'):
    sys.exit('The key section of tools/ai_prompt.md has a new shape: check this script.')
m = re.search(r'A címke fehérjéje a `protein`-be kerül[^\n]*?\.(?=\n|$)', bullets)
if not m:
    sys.exit('The sentence about `protein` is missing in the key list of tools/ai_prompt.md')
note = m.group(0)
a = head + '## Tápanyagkulcsok\n\n' + intro
if '(v1)' not in a.splitlines()[0]:
    sys.exit('The title of tools/ai_prompt.md has no "(v1)": check this script and AI_IMPORT_VERSION.')


def js(s):
    return s.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')


a_js = js(a).replace('(v1)', '(v${AI_IMPORT_VERSION})', 1)
block = ('/* >>> AI prompt: written by tools/embed_ai_prompt.py from tools/ai_prompt.md. Do not edit by hand. */\n'
         f'const AI_PROMPT_A = `{a_js}`;\n'
         f'const AI_PROMPT_NOTE = `{js(note)}`;\n'
         f'const AI_PROMPT_B = `{js(tail.rstrip())}`;\n'
         '/* <<< AI prompt */')
new, n = re.subn(r'/\* >>> AI prompt.*?/\* <<< AI prompt \*/', lambda _: block, app, count=1, flags=re.S)
if n != 1:
    sys.exit('The marker comments "/* >>> AI prompt" and "/* <<< AI prompt */" were not found in app.js')
app_path.write_text(new, encoding='utf-8')
print('app.js updated:', len(a) + len(note) + len(tail), 'characters of prompt')
